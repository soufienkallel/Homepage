// Shared zod schemas and TS types for @mallouliauto/agents
// See doc/requirements/mallouliauto_agents_specifications.md §4

import { z } from 'zod';

export const AgentTypeSchema = z.enum(['marketing', 'sales']);
export type AgentType = z.infer<typeof AgentTypeSchema>;

export const AgentChannelSchema = z.enum([
  'linkedin',
  'facebook',
  'instagram',
  'email',
  'linkedin_dm',
  'whatsapp',
]);
export type AgentChannel = z.infer<typeof AgentChannelSchema>;

export const AgentLanguageSchema = z.enum(['fr', 'ar', 'en']);
export type AgentLanguage = z.infer<typeof AgentLanguageSchema>;

export const AgentSegmentSchema = z.enum(['insurance', 'garage', 'dealer', 'fleet', 'b2c']);
export type AgentSegment = z.infer<typeof AgentSegmentSchema>;

export const AgentDraftStatusSchema = z.enum([
  'pending_review',
  'approved',
  'rejected',
  'published',
]);
export type AgentDraftStatus = z.infer<typeof AgentDraftStatusSchema>;

export const ProspectStatusSchema = z.enum([
  'new',
  'sequence_generated',
  'in_progress',
  'replied',
  'demo_booked',
  'won',
  'lost',
  'unsubscribed',
]);
export type ProspectStatus = z.infer<typeof ProspectStatusSchema>;

export const DraftContentSchema = z.object({
  subject: z.string().optional(),
  body: z.string().min(1),
  hashtags: z.array(z.string()).optional(),
  image_brief: z.string().optional(),
  image_spec: z
    .object({
      template: z.enum([
        'vision_result',
        'diagnostic_result',
        'fleet_dashboard',
        'stat_card',
        'booking_flow',
        'recruitment',
      ]),
      headline: z.string(),
      subheadline: z.string().optional(),
      stats: z.array(z.object({ label: z.string(), value: z.string() })).optional(),
      icon: z.string().optional(),
      accent: z.enum(['blue', 'orange']).optional(),
    })
    .optional(),
  // Puppeteer-rendered image: full HTML document generated by Claude
  image_html: z.string().optional(),
  // Ready-to-use prompt for external AI image generation (DALL-E 3 / Gemini Imagen)
  image_prompt: z.string().optional(),
  scheduled_for: z.string().datetime().optional(),
});
export type DraftContent = z.infer<typeof DraftContentSchema>;

export type ImageSpec = NonNullable<DraftContent['image_spec']>;
export type ImageTemplate = ImageSpec['template'];

export const GuardrailReportSchema = z.object({
  passed: z.boolean(),
  warnings: z.array(z.string()),
  blocked_reasons: z.array(z.string()),
});
export type GuardrailReport = z.infer<typeof GuardrailReportSchema>;
